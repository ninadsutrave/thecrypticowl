-- ─── 2. MECHANICAL VERIFICATION FLAG ─────────────────────────────────────────
-- TRUE when the wordplay arithmetic was PROVED in code (sorted-letter match
-- for an anagram, literal embedding for a hidden word, exact concatenation for
-- a charade, and so on) rather than assessed by a language model.
--
-- Worth storing rather than deriving: it lets us measure what share of the
-- archive rests on deterministic proof versus model judgement, and makes a
-- regression in the verifier visible as a drop in that share rather than as
-- scattered complaints about broken clues.
--
-- NULL means the clue predates this migration; FALSE means the mechanism is
-- not decidable in code (homophone, spoonerism, &lit, compound) or the fodder
-- was a synonym the verifier could not resolve.

ALTER TABLE clues
  ADD COLUMN IF NOT EXISTS mechanically_verified BOOLEAN;

COMMENT ON COLUMN clues.mechanically_verified IS
  'TRUE when the wordplay arithmetic was proved deterministically in code '
  '(see lambda/core/validator/mechanics.js), FALSE when only the AI judge '
  'assessed it, NULL for clues created before verification existed.';

-- Supports "how much of the archive is code-verified?" without scanning.
CREATE INDEX IF NOT EXISTS clues_mechanically_verified_idx
  ON clues (mechanically_verified)
  WHERE mechanically_verified IS NOT NULL;


-- ─── 3. QUALITY REPORTING VIEW ───────────────────────────────────────────────
-- One row per wordplay mechanism: how many clues, how well the judge scored
-- them, and what share had their arithmetic proved in code. This is the view
-- to check after changing a generator prompt — a mechanism whose
-- verified_pct falls is producing clues the verifier can no longer confirm.

CREATE OR REPLACE VIEW clue_quality_by_mechanism AS
SELECT
  c.primary_type                                              AS mechanism,
  COUNT(*)                                                    AS total_clues,
  ROUND(AVG(c.judge_score)::NUMERIC, 2)                       AS avg_judge_score,
  ROUND(AVG(c.judge_surface_quality)::NUMERIC, 2)             AS avg_surface_quality,
  COUNT(*) FILTER (WHERE c.mechanically_verified)             AS code_verified,
  ROUND(
    100.0 * COUNT(*) FILTER (WHERE c.mechanically_verified) / NULLIF(COUNT(*), 0),
    1
  )                                                           AS verified_pct,
  COUNT(*) FILTER (WHERE c.judge_wordplay_correct IS FALSE)   AS wordplay_flagged,
  MIN(c.judge_score)                                          AS worst_score
FROM clues c
GROUP BY c.primary_type;

REVOKE ALL ON clue_quality_by_mechanism FROM PUBLIC;
GRANT SELECT ON clue_quality_by_mechanism TO authenticated;
